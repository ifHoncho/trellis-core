// Package wpa renders wpa_supplicant configuration for an 802.11s mesh with
// SAE and speaks the wpa_supplicant control-interface protocol.
package wpa

import (
	"context"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"strings"
	"time"
)

// MeshConfig is everything needed for one mesh interface.
type MeshConfig struct {
	CtrlDir    string
	MeshID     string
	Passphrase string
	FreqMHz    int
	WidthMHz   int // 20, 40, 80 or 160
	// Country is the regulatory domain in force (the profile's), written
	// as wpa_supplicant's global country. Without it wpa_supplicant handles
	// no radar for a mesh: it refuses a channel that needs radar detection
	// ("not allowed for AP mode"), because it switches
	// on ieee80211h and the channel availability check only when a country
	// is set (wpa_supplicant/mesh.c).
	Country string
	// MeshFwding enables 802.11s layer-2 forwarding. Trellis keeps it off:
	// batman-adv owns all paths (architecture §5).
	MeshFwding bool
	// Optional tuning. Zero values leave wpa_supplicant's defaults.
	BeaconIntTU   int
	BasicRates    []int // in 100 kbit/s units, e.g. 60 120 240
	RSSIThreshold *int  // dBm; peers below are not connected (0 disables)
	MaxPeerLinks  int
	// NoHTOverrides is set when wpa_supplicant was built without
	// CONFIG_HT_OVERRIDES (Fedora's, for one): it rejects the whole file on
	// disable_ht40. See HTOverrides.
	NoHTOverrides bool
	// S1G makes this a Wi-Fi HaLow mesh, for Morse Micro's wpa_supplicant_s1g
	// (S1GBinary). FreqMHz and WidthMHz are then unused: that supplicant
	// takes the S1G channel below, maps it to a 5 GHz channel for cfg80211
	// itself, and tells the driver the real one.
	S1G *S1GParams
}

// S1GBinary is Morse Micro's fork of wpa_supplicant, the only one that can
// start an S1G (HaLow) mesh on Morse's driver. scripts/install-halow-tools.sh
// builds it.
const S1GBinary = "wpa_supplicant_s1g"

// S1GParams are the settings only wpa_supplicant_s1g knows.
type S1GParams struct {
	Country string // two letters; the S1G channel plan depends on it
	OpClass int    // global operating class
	Channel int    // S1G channel number
	// The primary channel inside an operating channel wider than 2 MHz,
	// which every node of the mesh must agree on: its width (1 or 2 MHz)
	// and the index of its 1 MHz channel within the operating channel.
	PrimaryWidthMHz int
	Primary1MHzIdx  int
}

// S1GPrimary is the primary channel Trellis uses for an operating width: the
// operating channel itself at 1 and 2 MHz, and the lowest 2 MHz of a wider
// one. Fixed, so every node derives the same one from the profile.
func S1GPrimary(widthMHz int) (primaryWidthMHz, primary1MHzIdx int) {
	if widthMHz <= 1 {
		return 1, 0
	}
	return 2, 0
}

// 80 MHz block centre channels in the 5 GHz band.
var centre80 = []int{42, 58, 106, 122, 138, 155, 171}

// CenterFreq80 returns the centre frequency of the 80 MHz block containing
// a 5 GHz primary channel frequency, or 0 if none.
func CenterFreq80(freqMHz int) int {
	for _, c := range centre80 {
		centre := 5000 + 5*c
		if freqMHz >= centre-40 && freqMHz < centre+40 {
			return centre
		}
	}
	return 0
}

// Render produces the wpa_supplicant configuration file contents.
func Render(c MeshConfig) string {
	var b strings.Builder
	b.WriteString("# Generated by trellis meshd. Changes are overwritten.\n")
	fmt.Fprintf(&b, "ctrl_interface=DIR=%s\n", c.CtrlDir)
	b.WriteString("update_config=0\n")
	b.WriteString("p2p_disabled=1\n")
	if c.MaxPeerLinks > 0 {
		fmt.Fprintf(&b, "max_peer_links=%d\n", c.MaxPeerLinks)
	}
	switch {
	case c.S1G != nil:
		fmt.Fprintf(&b, "country=%s\n", c.S1G.Country)
		// SAE with hash-to-element only, as Morse Micro's own configurations
		// have it for HaLow.
		b.WriteString("sae_pwe=1\n")
	case c.Country != "":
		fmt.Fprintf(&b, "country=%s\n", c.Country)
	}
	b.WriteString("\nnetwork={\n")
	// Hex form avoids every quoting question for the mesh ID.
	fmt.Fprintf(&b, "\tssid=%s\n", hex.EncodeToString([]byte(c.MeshID)))
	b.WriteString("\tmode=5\n")
	if c.S1G != nil {
		fmt.Fprintf(&b, "\tcountry=\"%s\"\n", c.S1G.Country)
		fmt.Fprintf(&b, "\top_class=%d\n", c.S1G.OpClass)
		fmt.Fprintf(&b, "\tchannel=%d\n", c.S1G.Channel)
		prim := 1 // s1g_prim_chwidth: 0 is a 1 MHz primary channel, 1 a 2 MHz one
		if c.S1G.PrimaryWidthMHz <= 1 {
			prim = 0
		}
		fmt.Fprintf(&b, "\ts1g_prim_chwidth=%d\n", prim)
		fmt.Fprintf(&b, "\ts1g_prim_1mhz_chan_index=%d\n", c.S1G.Primary1MHzIdx)
	} else {
		fmt.Fprintf(&b, "\tfrequency=%d\n", c.FreqMHz)
	}
	b.WriteString("\tkey_mgmt=SAE\n")
	fmt.Fprintf(&b, "\tsae_password=\"%s\"\n", c.Passphrase)
	b.WriteString("\tieee80211w=2\n")
	if c.MeshFwding {
		b.WriteString("\tmesh_fwding=1\n")
	} else {
		b.WriteString("\tmesh_fwding=0\n")
	}
	// Above 2.4 GHz a 20 or 40 MHz mesh also needs VHT switched on and held
	// to the HT width (max_oper_chwidth=0). Left to itself, wpa_supplicant
	// 2.10 widens a 40 MHz mesh to 80 MHz on a VHT radio, and cannot start a
	// 20 MHz one at all on an 802.11ax radio: it asks for HE without VHT
	// and without a width ("mesh join error=-1").
	// A radio without VHT ignores both settings.
	hold := ""
	if c.FreqMHz >= 5000 {
		hold = "\tvht=1\n\tmax_oper_chwidth=0\n"
	}
	switch {
	case c.S1G != nil:
		// The operating class carries the width.
	case c.WidthMHz == 40:
		b.WriteString("\tht40=1\n" + hold)
	case c.WidthMHz == 80:
		b.WriteString("\tht40=1\n")
		b.WriteString("\tvht=1\n")
		b.WriteString("\tmax_oper_chwidth=1\n")
		if cf := CenterFreq80(c.FreqMHz); cf != 0 {
			fmt.Fprintf(&b, "\tvht_center_freq1=%d\n", cf)
		}
	case c.WidthMHz == 160:
		// wpa_supplicant places the 160 MHz block itself, and narrows the
		// mesh to 80 MHz where it cannot. 2.10 builds 160 MHz only from
		// channel 36 or 104; later versions also from any block an HE radio
		// and the regulatory domain allow. meshd reports the width the
		// interface runs at.
		b.WriteString("\tht40=1\n")
		b.WriteString("\tvht=1\n")
		b.WriteString("\tmax_oper_chwidth=2\n")
	default:
		if c.NoHTOverrides {
			// Without HT overrides nothing holds a mesh to 20 MHz:
			// wpa_supplicant 2.11 picks HT40 on 5 GHz whenever the channel
			// has a partner, and reads ht40 only as an output in mesh mode.
			// max_oper_chwidth=0 (HT only) at least rules out 80 MHz. On
			// 2.4 GHz it never goes beyond 20 MHz.
			b.WriteString("\tmax_oper_chwidth=0\n")
		} else {
			b.WriteString("\tdisable_ht40=1\n" + hold)
		}
	}
	if c.BeaconIntTU > 0 {
		fmt.Fprintf(&b, "\tbeacon_int=%d\n", c.BeaconIntTU)
	}
	if c.S1G != nil {
		// wpa_supplicant_s1g refuses to start a mesh with any other DTIM
		// period, its own default (0) included: "Invalid DTIM period (0) for
		// Mesh, set (1)", then "Could not join mesh".
		b.WriteString("\tdtim_period=1\n")
	}
	if len(c.BasicRates) > 0 {
		parts := make([]string, len(c.BasicRates))
		for i, r := range c.BasicRates {
			parts[i] = fmt.Sprint(r)
		}
		fmt.Fprintf(&b, "\tmesh_basic_rates=%s\n", strings.Join(parts, " "))
	}
	if c.RSSIThreshold != nil {
		fmt.Fprintf(&b, "\tmesh_rssi_threshold=%d\n", *c.RSSIThreshold)
	}
	b.WriteString("}\n")
	return b.String()
}

// PassphraseOK reports whether a passphrase can be written into a quoted
// wpa_supplicant string without escaping: printable ASCII, no quotes or
// backslashes.
func PassphraseOK(s string) error {
	for i, r := range s {
		if r < 0x20 || r > 0x7e {
			return fmt.Errorf("character %d is not printable ASCII", i+1)
		}
		if r == '"' || r == '\\' {
			return fmt.Errorf("character %d (%q) is not allowed", i+1, r)
		}
	}
	return nil
}

// HTOverrides reports whether the wpa_supplicant at path accepts
// disable_ht40, that is, was built with CONFIG_HT_OVERRIDES. It test-parses
// a minimal mesh network block: wpa_supplicant reads its configuration before
// it touches the driver, so a nonexistent interface is enough and nothing is
// changed. dir holds the probe file. On error it returns true, which keeps
// the configuration every Debian-family build accepts.
func HTOverrides(ctx context.Context, path, dir string) (bool, error) {
	f, err := os.CreateTemp(dir, "wpa-probe-*.conf")
	if err != nil {
		return true, err
	}
	defer os.Remove(f.Name())
	probe := "update_config=0\np2p_disabled=1\n\nnetwork={\n\tssid=7472656c6c6973\n\tmode=5\n\tfrequency=2412\n" +
		"\tkey_mgmt=SAE\n\tsae_password=\"trellis-probe\"\n\tdisable_ht40=1\n}\n"
	if _, err := f.WriteString(probe); err != nil {
		f.Close()
		return true, err
	}
	if err := f.Close(); err != nil {
		return true, err
	}
	ctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	// It always fails (no such interface); only its messages matter.
	out, _ := exec.CommandContext(ctx, path, "-i", "trellis-probe0", "-D", "nl80211", "-c", f.Name()).CombinedOutput()
	if ctx.Err() != nil {
		return true, fmt.Errorf("probe %s: %w", path, ctx.Err())
	}
	return htOverridesFromProbe(string(out)), nil
}

// htOverridesFromProbe reads HTOverrides' probe output.
func htOverridesFromProbe(out string) bool {
	return !strings.Contains(out, "unknown network field 'disable_ht40'")
}
