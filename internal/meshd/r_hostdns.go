// The node's own DNS while it has no uplink of its own. Its clients ask the
// node's dnsmasq (on the anycast address), which forwards to the gateway in
// use; the node itself asks whatever its system was last given, often the
// resolver of a LAN it is no longer on. While the node has no default route
// of its own (its own traffic then leaves through the gateway in use,
// prioLast), meshd points the system's resolver at the node's dnsmasq too,
// and puts it back when the node has an uplink again or meshd stops:
//
//   - systemd-resolved: a DNS server and the "~." routing domain on the
//     mesh bridge (run-time only, gone with a resolved restart, so checked
//     again every minute);
//   - NetworkManager writing /etc/resolv.conf: a global DNS setting in its
//     conf.d.
//
// Anything else is left alone, and the node says so.

const (
	nmDNSConf        = "/etc/NetworkManager/conf.d/90-trellis-dns.conf"
	hostDNSRecheck   = time.Minute
	resolvedStubPath = "/run/systemd/resolve/"
)

// hostResolver says which resolver stack writes /etc/resolv.conf: "resolved",
// "networkmanager", or "".
func hostResolver(root string) string {
	conf := filepath.Join(root, "etc/resolv.conf")
	if target, err := filepath.EvalSymlinks(conf); err == nil && strings.HasPrefix(target, filepath.Join(root, resolvedStubPath)) {
		return "resolved"
	}
	data, err := os.ReadFile(conf)
	if err == nil && bytes.Contains(data, []byte("Generated by NetworkManager")) {
		if _, err := exec.LookPath("nmcli"); err == nil {
			return "networkmanager"
		}
	}
	return ""
}

// nmDNSConfig is the NetworkManager setting that sends the system's DNS to
// server.
func nmDNSConfig(server string) []byte {
	return []byte("# Written by Trellis meshd while this node has no uplink of its own: the\n" +
		"# system's DNS goes to the node's own mesh DNS, which forwards to the\n" +
		"# gateway in use. meshd removes it when the node has an uplink again.\n" +
		"[global-dns-domain-*]\nservers=" + server + "\n")
}

// mainHasDefault reports whether the main routing table has a default
// route: then the system has an uplink of its own, and its DNS is its own.
func mainHasDefault() bool {
	routes, err := netlink.RouteListFiltered(netlink.FAMILY_V4, &netlink.Route{Table: unix.RT_TABLE_MAIN}, netlink.RT_FILTER_TABLE)
	if err != nil {
		return true // unknown: leave the system alone
	}
	for _, r := range routes {
		if r.Dst == nil || (r.Dst.IP.Equal(net.IPv4zero) && isZeroMask(r.Dst.Mask)) {
			return true
		}
	}
	return false
}

func isZeroMask(m net.IPMask) bool {
	ones, _ := m.Size()
	return ones == 0
}

// applyHostDNS points the system's resolver at server (want) or puts it
// back, and reports whether it changed anything.
func (g *gatewayReconciler) applyHostDNS(ctx context.Context, want bool, server string, warn func(level, code, format string, args ...any)) bool {
	d := g.d
	if d.opts.NoHostConfig {
		return false
	}
	if g.hostDNSKind == "" {
		root := g.hostRoot
		if root == "" {
			root = "/"
		}
		if g.hostDNSKind = hostResolver(root); g.hostDNSKind == "" {
			g.hostDNSKind = "none"
		}
	}
	run := func(name string, args ...string) error {
		cctx, cancel := context.WithTimeout(ctx, 5*time.Second)
		defer cancel()
		out, err := exec.CommandContext(cctx, name, args...).CombinedOutput()
		if err != nil {
			return fmt.Errorf("%s %s: %v: %s", name, strings.Join(args, " "), err, strings.TrimSpace(string(out)))
		}
		return nil
	}
	switch g.hostDNSKind {
	case "resolved":
		if !want {
			if g.hostDNSOn == "" {
				return false
			}
			_ = run("resolvectl", "revert", BridgeIfname)
			d.log.Info("the system's DNS is its own again (the node has an uplink, or meshd stops)")
			g.hostDNSOn = ""
			return true
		}
		if g.hostDNSOn == server && time.Since(g.hostDNSAt) < hostDNSRecheck {
			return false
		}
		// Applied already: still in place after a resolved restart, or a
		// new bridge?
		if g.hostDNSOn == server {
			cctx, cancel := context.WithTimeout(ctx, 5*time.Second)
			out, err := exec.CommandContext(cctx, "resolvectl", "dns", BridgeIfname).Output()
			cancel()
			g.hostDNSAt = time.Now()
			if err == nil && strings.Contains(string(out), server) {
				return false
			}
		}
		for _, args := range [][]string{{"dns", BridgeIfname, server}, {"domain", BridgeIfname, "~."}, {"default-route", BridgeIfname, "yes"}} {
			if err := run("resolvectl", args...); err != nil && args[0] != "default-route" {
				warn("warning", "host-dns", "this node has no uplink of its own and its DNS cannot be sent to the mesh: %v", err)
				return false
			}
		}
		if g.hostDNSOn != server {
			d.log.Info("no uplink of its own: the system's DNS goes to the mesh", "server", server, "through", "systemd-resolved")
		}
		g.hostDNSOn, g.hostDNSAt = server, time.Now()
		return true
	case "networkmanager":
		have, _ := os.ReadFile(nmDNSConf)
		if !want {
			if have == nil {
				g.hostDNSOn = ""
				return false
			}
			if err := os.Remove(nmDNSConf); err != nil {
				warn("warning", "host-dns", "cannot remove %s: %v", nmDNSConf, err)
				return false
			}
			_ = run("nmcli", "general", "reload")
			d.log.Info("the system's DNS is its own again (the node has an uplink, or meshd stops)")
			g.hostDNSOn = ""
			return true
		}
		conf := nmDNSConfig(server)
		if bytes.Equal(have, conf) {
			g.hostDNSOn = server
			return false
		}
		if err := writeFileAtomic(nmDNSConf, conf, 0o644); err != nil {
			warn("warning", "host-dns", "this node has no uplink of its own and its DNS cannot be sent to the mesh: %v", err)
			return false
		}
		if err := run("nmcli", "general", "reload"); err != nil {
			warn("warning", "host-dns", "NetworkManager did not take the mesh DNS: %v", err)
		}
		d.log.Info("no uplink of its own: the system's DNS goes to the mesh", "server", server, "through", "NetworkManager")
		g.hostDNSOn = server
		return true
	}
	if want {
		warn("info", "host-dns", "this node has no uplink of its own and its resolver is neither systemd-resolved nor NetworkManager: its own DNS is left as it is (the mesh's DNS is %s)", server)
	}
	return false
}
