// The resolver stack is told by what /etc/resolv.conf is: a link into
// systemd-resolved's run directory (Ubuntu, Armbian), or a file
// NetworkManager wrote (Raspberry Pi OS).
func TestHostResolver(t *testing.T) {
	mk := func(t *testing.T, link, content string) string {
		root := t.TempDir()
		os.MkdirAll(filepath.Join(root, "etc"), 0o755)
		os.MkdirAll(filepath.Join(root, "run/systemd/resolve"), 0o755)
		os.WriteFile(filepath.Join(root, "run/systemd/resolve/stub-resolv.conf"), []byte("nameserver 127.0.0.53\n"), 0o644)
		if link != "" {
			os.Symlink(filepath.Join(root, link), filepath.Join(root, "etc/resolv.conf"))
		} else {
			os.WriteFile(filepath.Join(root, "etc/resolv.conf"), []byte(content), 0o644)
		}
		return root
	}
	if got := hostResolver(mk(t, "run/systemd/resolve/stub-resolv.conf", "")); got != "resolved" {
		t.Errorf("stub link: %q", got)
	}
	if got := hostResolver(mk(t, "", "nameserver 192.0.2.1\n")); got != "" {
		t.Errorf("a plain file: %q", got)
	}
	nm := mk(t, "", "# Generated by NetworkManager\nsearch lan\nnameserver 192.0.2.1\n")
	want := "networkmanager"
	if _, err := os.Stat("/usr/bin/nmcli"); err != nil {
		want = "" // without nmcli on this machine it cannot be driven
	}
	if got := hostResolver(nm); got != want {
		t.Errorf("NetworkManager's file: %q, want %q", got, want)
	}
	if c := string(nmDNSConfig("10.73.0.1")); !strings.Contains(c, "[global-dns-domain-*]\nservers=10.73.0.1\n") {
		t.Errorf("NetworkManager setting:\n%s", c)
	}
}

// The system's DNS is pointed at the node's dnsmasq only once dnsmasq
// forwards to the mesh, never while it forwards to a resolver on this host.
func TestForwardsToMesh(t *testing.T) {
	for up, want := range map[string]bool{
		"10.73.2.1": true, "10.73.2.1,10.73.129.1": true, "192.0.2.53@eth1": true,
		"": false, "127.0.0.53": false, "10.73.2.1,127.0.0.53": false, "::1": false,
	} {
		var ups []string
		if up != "" {
			ups = strings.Split(up, ",")
		}
		if got := forwardsToMesh(ups); got != want {
			t.Errorf("%q: %v, want %v", up, got, want)
		}
	}
}
